"""Version 0001: create the append-only gateway and backfill historical records."""

from sqlalchemy import text

from app.db.session import protect_postgres_tables

VERSION = "0001_verified_evidence"

DDL = (
    """
    CREATE TABLE record_provenance (
        id VARCHAR(36) PRIMARY KEY,
        business_id VARCHAR(36) NOT NULL REFERENCES businesses(id),
        source_id VARCHAR(36) REFERENCES data_sources(id),
        transaction_id VARCHAR(36) UNIQUE REFERENCES transactions(id) ON DELETE CASCADE,
        invoice_id VARCHAR(36) UNIQUE REFERENCES invoices(id) ON DELETE CASCADE,
        obligation_id VARCHAR(36) UNIQUE REFERENCES obligations(id) ON DELETE CASCADE,
        source_type VARCHAR(24) NOT NULL,
        source_provider VARCHAR(120),
        original_source_reference VARCHAR(100),
        uploaded_at TIMESTAMP,
        file_sha256 VARCHAR(64),
        consent_reference VARCHAR(160),
        CONSTRAINT ck_provenance_one_record CHECK (num_nonnulls(transaction_id, invoice_id, obligation_id) = 1),
        CONSTRAINT ck_provenance_source_type CHECK (
            source_type IN ('USER_UPLOAD', 'INSTITUTIONAL', 'SIMULATED', 'LEGACY_UNKNOWN')
        ),
        CONSTRAINT ck_provenance_file_hash_length CHECK (file_sha256 IS NULL OR length(file_sha256) = 64)
    )
    """,
    "CREATE INDEX ix_record_provenance_business_id ON record_provenance (business_id)",
    "CREATE INDEX ix_record_provenance_source_id ON record_provenance (source_id)",
    """
    CREATE TABLE verification_events (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        provenance_id VARCHAR(36) NOT NULL REFERENCES record_provenance(id) ON DELETE CASCADE,
        method VARCHAR(40) NOT NULL,
        status VARCHAR(30) NOT NULL,
        verified_at TIMESTAMP NOT NULL,
        findings JSON NOT NULL,
        supporting_evidence JSON NOT NULL,
        limitations JSON NOT NULL,
        CONSTRAINT ck_verification_status CHECK (status IN (
            'UNVERIFIED', 'PARTIALLY_SUPPORTED', 'SOURCE_VERIFIED', 'REQUIRES_REVIEW', 'SIMULATED_SOURCE_VERIFIED'
        )),
        CONSTRAINT ck_verification_source_method CHECK (
            (status <> 'SOURCE_VERIFIED' OR method = 'institutional_authentication') AND
            (status <> 'SIMULATED_SOURCE_VERIFIED' OR method = 'simulated_fixture')
        )
    )
    """,
    "CREATE INDEX ix_verification_history ON verification_events (provenance_id, id)",
)

BACKFILL = """
    WITH historical AS (
        SELECT business_id, source_id, id AS transaction_id, NULL::varchar AS invoice_id,
               NULL::varchar AS obligation_id, external_ref AS reference FROM transactions
        UNION ALL
        SELECT business_id, source_id, NULL, id, NULL, invoice_no FROM invoices
        UNION ALL
        SELECT business_id, NULL, NULL, NULL, id, NULL FROM obligations
    ), captured AS (
        INSERT INTO record_provenance (
            id, business_id, source_id, transaction_id, invoice_id, obligation_id,
            source_type, source_provider, original_source_reference, uploaded_at, file_sha256
        )
        SELECT gen_random_uuid()::text, h.business_id, s.id, h.transaction_id, h.invoice_id, h.obligation_id,
               CASE WHEN s.synthetic THEN 'SIMULATED' WHEN s.id IS NULL THEN 'LEGACY_UNKNOWN' ELSE 'USER_UPLOAD' END,
               CASE WHEN s.synthetic THEN 'CredWeave synthetic fixture' END,
               h.reference, CASE WHEN NOT s.synthetic THEN s.imported_at END,
               CASE WHEN s.file_hash ~ '^[0-9a-f]{64}$' THEN s.file_hash END
        FROM historical h
        LEFT JOIN data_sources s ON s.id = h.source_id AND s.business_id = h.business_id
        RETURNING id
    )
    INSERT INTO verification_events (
        provenance_id, method, status, verified_at, findings, supporting_evidence, limitations
    )
    SELECT id, 'historical_backfill', 'UNVERIFIED', timezone('UTC', now()),
           '[{"code":"LEGACY_RECORD","reason":"Original validation results were not recorded."}]'::json,
           '[]'::json,
           '["Historical source metadata may be incomplete. No independent verification is recorded."]'::json
    FROM captured
"""


def apply(connection) -> None:
    connection.execute(text("LOCK TABLE transactions, invoices, obligations IN SHARE ROW EXCLUSIVE MODE"))
    for statement in DDL:
        connection.execute(text(statement))
    protect_postgres_tables(connection, ["record_provenance", "verification_events"])
    connection.execute(text(BACKFILL))
